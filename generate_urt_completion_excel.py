def status_fill(status):
    s = str(status)
    if "已完成" in s or "已落地" in s or "已交付" in s:
        return THEME["done"]
    if "部分" in s:
        return THEME["partial"]
    if "进行" in s or "待验证" in s or "跟踪" in s:
        return THEME["doing"]
    if "计划" in s or "体验增强" in s:
        return THEME["planned"]
    if "未实现" in s or "待开发" in s or "待产品确认" in s or "待确认" in s:
        return THEME["todo"]
    return "FFFFFF"


def write_table(wb, title, rows, widths=None, status_col=None):
    ws = wb.create_sheet(title)
    for row in rows:
        ws.append(row)
    style_sheet(ws)
    if status_col:
        for row in range(2, ws.max_row + 1):
            cell = ws.cell(row=row, column=status_col)
            cell.fill = PatternFill("solid", fgColor=status_fill(cell.value))
            cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    if widths:
        for idx, width in enumerate(widths, 1):
            ws.column_dimensions[get_column_letter(idx)].width = width
    else:
        for col in range(1, ws.max_column + 1):
            ws.column_dimensions[get_column_letter(col)].width = 18
    for row in range(1, ws.max_row + 1):
        ws.row_dimensions[row].height = 28 if row == 1 else 40
    return ws


